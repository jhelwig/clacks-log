//! Publication copy of implemented desktop sync contracts.

use clacks_sync::protocol::contracts::SyncContract;
use strum::IntoEnumIterator;

/// Implemented support serialized deterministically for browser publication.
#[derive(serde::Serialize)]
struct Declaration {
    /// Identifiers of the implementations compiled into desktop negotiation.
    sync_contracts: Vec<&'static str>,
}

/// Generate the publication bytes from the implemented contract variants.
pub(crate) fn generate() -> anyhow::Result<Vec<u8>> {
    let declaration = Declaration {
        sync_contracts: SyncContract::iter().map(SyncContract::id).collect(),
    };

    let mut bytes = serde_json::to_vec_pretty(&declaration)?;
    bytes.push(b'\n');
    Ok(bytes)
}

/// Write the shared generated bytes to the caller's publication path.
pub(crate) fn write(output: &std::path::Path) -> anyhow::Result<()> {
    if let Some(parent) = output.parent().filter(|path| !path.as_os_str().is_empty()) {
        std::fs::create_dir_all(parent)?;
    }

    std::fs::write(output, generate()?)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    #[test]
    fn committed_metadata_matches_implemented_contracts() -> anyhow::Result<()> {
        let expected = super::generate()?;
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../deploy/desktop/sync-contracts.json");
        let actual = std::fs::read(path).map_err(|error| anyhow::anyhow!(
            "{error}; regenerate with cargo run --bin clacks-desktop-package -- sync-contracts --output deploy/desktop/sync-contracts.json"
        ))?;

        assert_eq!(
            actual, expected,
            "regenerate with cargo run --bin clacks-desktop-package -- sync-contracts --output deploy/desktop/sync-contracts.json"
        );
        Ok(())
    }
}
