//! Reproducible test-only LoTW data, independently constructed in Rust.

mod archives;
mod certificates;
mod signing;

use anyhow::{Context, ensure};
use rsa::pkcs8::{EncodePrivateKey, EncodePublicKey, LineEnding};
use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
};

#[cfg(test)]
mod tests;

/// Usage for the dedicated, deterministic fixture-authoring executable.
const HELP: &str =
    "clacks-lotw-fixtures - generate or verify reproducible Rust-authored LoTW fixtures

Usage: clacks-lotw-fixtures [--check | --write | --help]

    --check  Reconstruct every fixture and compare its exact committed bytes
    --write  Replace fixture files with deterministic Rust-generated bytes
    --help   Show help (also shown with no arguments)

Use the locked toolchain and dependencies, preferably with --release.
All keys, random seeds, salts and IVs are public test-only constants.
Never use them for real credentials. No external tools or TQSL execution occur.
";

/// Generate or verify all fixture bytes using only project-owned Rust tooling.
///
/// No arguments or `--help` prints usage. `--write` explicitly replaces files;
/// `--check` returns an error for changed, missing or unowned fixture files.
/// Construction reads fixed key inputs embedded from this tool's source tree,
/// never the existing output bytes or production import, signing or serialization.
/// Use the committed lockfile for reproducibility.
pub fn run(arguments: impl IntoIterator<Item = String>) -> anyhow::Result<()> {
    let mut arguments = arguments.into_iter();
    let action = arguments.next();
    ensure!(arguments.next().is_none(), "{HELP}");
    let check = match action.as_deref() {
        None | Some("--help") => {
            print!("{HELP}");
            return Ok(());
        }
        Some("--check") => true,
        Some("--write") => false,
        Some(_) => anyhow::bail!("{HELP}"),
    };
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .context("fixture library must be under lib/")?
        .join("lib/clacks-lotw/tests/fixtures");
    let files = generate()?;
    let mut existing = Vec::new();
    collect(&root, &root, &mut existing)?;
    for path in existing {
        ensure!(
            files.contains_key(&path),
            "fixture has no Rust construction recipe: {}",
            path.display()
        );
    }
    for (path, bytes) in &files {
        let target = root.join(path);
        if check {
            ensure!(
                fs::read(&target).with_context(|| format!("read fixture {}", path.display()))?
                    == *bytes,
                "fixture differs from Rust construction: {}",
                path.display()
            );
        } else {
            fs::create_dir_all(target.parent().context("fixture path has no parent")?)?;
            fs::write(&target, bytes)?;
        }
    }
    println!(
        "{} {} reproducible Rust fixtures",
        if check { "Verified" } else { "Wrote" },
        files.len()
    );
    Ok(())
}

/// List current data files so obsolete or unreproducible inputs cannot be ignored.
fn collect(root: &Path, directory: &Path, files: &mut Vec<PathBuf>) -> anyhow::Result<()> {
    for entry in fs::read_dir(directory)? {
        let path = entry?.path();
        if path.is_dir() {
            collect(root, &path, files)?;
        } else if path.file_name().is_none_or(|n| n != "README.md") {
            files.push(path.strip_prefix(root)?.to_owned());
        }
    }
    Ok(())
}

/// Construct every certificate, archive, signature and literal wire expectation.
#[tracing::instrument(skip_all, name = "fixtures.lotw.construct", level = "debug")]
fn generate() -> anyhow::Result<BTreeMap<PathBuf, Vec<u8>>> {
    let mut files = BTreeMap::new();
    let issuer = signing::key(include_str!("fixtures/keys/issuer.pem"))?;
    let mut primary = None;
    let mut other_key = None;
    let mut other_certificate = None;
    for (bits, pem) in [
        (1024, include_str!("fixtures/keys/station-1024.pem")),
        (2048, include_str!("fixtures/keys/station-2048.pem")),
        (4096, include_str!("fixtures/keys/station-4096.pem")),
    ] {
        let key = signing::key(pem)?;
        let der = key.to_pkcs8_der()?;
        let cert = certificates::station(&key, &issuer, "")?;
        let signature = signing::sign(&key, signing::INPUT)?;
        files.insert(
            PathBuf::from(format!("{bits}/test-key.pem")),
            key.to_pkcs8_pem(LineEnding::LF)?.as_bytes().to_vec(),
        );
        files.insert(
            PathBuf::from(format!("{bits}/public.pem")),
            key.to_public_key()
                .to_public_key_pem(LineEnding::LF)?
                .into_bytes(),
        );
        files.insert(PathBuf::from(format!("{bits}/station.der")), cert.clone());
        files.insert(
            PathBuf::from(format!("{bits}/normal.p12")),
            archives::encrypted(
                &cert,
                der.as_bytes(),
                archives::PASSWORD,
                false,
                false,
                2048,
            )?,
        );
        files.insert(
            PathBuf::from(format!("{bits}/legacy.p12")),
            archives::encrypted(&cert, der.as_bytes(), archives::PASSWORD, true, false, 2048)?,
        );
        files.insert(
            PathBuf::from(format!("{bits}/known-signature.bin")),
            signature.clone(),
        );
        if bits == 1024 {
            files.insert(
                "single-contact.gabbi".into(),
                signing::wire(&cert, &signature),
            );
            primary = Some((key, cert));
        } else if bits == 2048 {
            other_key = Some(der.as_bytes().to_vec());
            other_certificate = Some(cert);
        }
    }
    let (key, cert) = primary.context("missing primary fixture key")?;
    let der = key.to_pkcs8_der()?;
    for (file, legacy) in [("normal-key-first", false), ("legacy-key-first", true)] {
        files.insert(
            format!("{file}.p12").into(),
            archives::encrypted(
                &cert,
                der.as_bytes(),
                archives::PASSWORD,
                legacy,
                true,
                2048,
            )?,
        );
    }
    for iterations in [1, 0, -1] {
        files.insert(
            format!("legacy-one-round-{iterations}.p12").into(),
            archives::encrypted(
                &cert,
                der.as_bytes(),
                archives::PASSWORD,
                true,
                false,
                iterations,
            )?,
        );
    }
    files.insert(
        "invalid-private-exponent.p12".into(),
        archives::plain(
            std::slice::from_ref(&cert),
            &altered_key(der.as_bytes(), "private_exponent", &[1])?,
            archives::PASSWORD,
            "",
        )?,
    );
    let other = other_key.context("missing alternate fixture key")?;
    let alternate_cert = other_certificate.context("missing alternate fixture certificate")?;
    let mut malformed = BTreeMap::new();
    files.insert(
        "no-expiry.der".into(),
        certificates::station(&key, &issuer, "no-expiry")?,
    );
    for name in [
        "common-name-only",
        "duplicate-callsign",
        "duplicate-coverage",
        "reversed-coverage",
        "invalid-date",
        "malformed-entity",
        "missing-coverage",
        "ec",
    ] {
        let bytes = certificates::station(&key, &issuer, name)?;
        files.insert(format!("{name}.der").into(), bytes.clone());
        malformed.insert(name, bytes);
    }
    for name in [
        "plain",
        "duplicate-bags",
        "misleading-alias",
        "no-mac",
        "mac-iterations-1000001",
        "mac-iterations-0",
        "mac-iterations--1",
        "mac-one-round-1",
        "mac-one-round-0",
        "mac-one-round--1",
    ] {
        let certs = if name == "duplicate-bags" {
            vec![cert.clone(), cert.clone()]
        } else {
            vec![cert.clone()]
        };
        files.insert(
            format!("{name}.p12").into(),
            archives::plain(&certs, der.as_bytes(), archives::PASSWORD, name)?,
        );
    }
    files.insert(
        "mismatch.p12".into(),
        archives::plain(std::slice::from_ref(&cert), &other, archives::PASSWORD, "")?,
    );
    files.insert(
        "ambiguous.p12".into(),
        archives::plain(
            &[cert.clone(), alternate_cert],
            der.as_bytes(),
            archives::PASSWORD,
            "",
        )?,
    );
    files.insert(
        "no-certificate.p12".into(),
        archives::plain(&[], der.as_bytes(), archives::PASSWORD, "")?,
    );
    for (file, variant) in [
        ("bad-metadata", "missing-coverage"),
        ("duplicate-callsign", "duplicate-callsign"),
        ("duplicate-coverage", "duplicate-coverage"),
    ] {
        let bytes = malformed
            .get(variant)
            .context("missing malformed certificate recipe")?;
        files.insert(
            format!("{file}.p12").into(),
            archives::plain(
                std::slice::from_ref(bytes),
                der.as_bytes(),
                archives::PASSWORD,
                "",
            )?,
        );
    }
    for name in [
        "unicode-expands",
        "unicode-remains",
        "control-call",
        "ascii-call",
    ] {
        files.insert(
            format!("{name}.p12").into(),
            archives::plain(
                &[certificates::station(&key, &issuer, name)?],
                der.as_bytes(),
                archives::PASSWORD,
                "",
            )?,
        );
    }
    for (name, password) in [("empty", ""), ("bmp", "test-café")] {
        files.insert(
            format!("{name}.p12").into(),
            archives::plain(std::slice::from_ref(&cert), der.as_bytes(), password, "")?,
        );
        files.insert(
            format!("encrypted-{name}.p12").into(),
            archives::encrypted(&cert, der.as_bytes(), password, false, false, 2048)?,
        );
    }
    files.insert(
        "supporting-ca.p12".into(),
        archives::plain(
            &[certificates::station(&issuer, &issuer, "ca")?, cert],
            der.as_bytes(),
            archives::PASSWORD,
            "",
        )?,
    );
    for name in [
        "modern-kdf-excessive",
        "legacy-kdf-excessive",
        "scrypt-excessive-memory",
        "scrypt-excessive-parallel",
        "unsupported-encryption",
    ] {
        files.insert(
            format!("{name}.p12").into(),
            archives::bounded(der.as_bytes(), name)?,
        );
    }
    let mut excessive_integer = vec![1];
    excessive_integer.extend(std::iter::repeat_n(0, 512));
    for name in ["modulus", "private_exponent"] {
        let oversized = altered_key(der.as_bytes(), name, &excessive_integer)?;
        files.insert(
            format!("oversized-{name}.p12").into(),
            archives::plain(
                &[certificates::station(&key, &issuer, "")?],
                &oversized,
                archives::PASSWORD,
                "",
            )?,
        );
    }
    files.insert("signing-input.txt".into(), signing::INPUT.to_vec());
    tracing::debug!(
        event = "fixtures.lotw.constructed",
        file_count = files.len()
    );
    Ok(files)
}

/// Encode a deliberately invalid RSA component without private-key validation.
fn altered_key(bytes: &[u8], component: &str, value: &[u8]) -> anyhow::Result<Vec<u8>> {
    use rsa::pkcs8::der::{Encode, asn1::UintRef};
    let mut info = rsa::pkcs8::PrivateKeyInfoRef::try_from(bytes)?;
    let mut key = rsa::pkcs1::RsaPrivateKeyRef::try_from(info.private_key.as_bytes())?;
    if component == "modulus" {
        key.modulus = UintRef::new(value)?;
    } else {
        key.private_exponent = UintRef::new(value)?;
    }
    let encoded = key.to_der()?;
    info.private_key = rsa::pkcs8::der::asn1::OctetStringRef::new(&encoded)?;
    Ok(info.to_der()?)
}
